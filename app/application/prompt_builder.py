class PromptBuilder:
    """Будує prompt для відповіді на основі контексту."""

    def build(
        self,
        question: str,
        subject: str,
        context: str,
    ) -> str:
        return f"""
Ти навчальний асистент. Відповідай лише на основі контексту нижче.

Якщо відповіді в контексті немає, скажи:
"У завантажених конспектах я не знайшла цієї інформації."

Не вигадуй факти та не використовуй зовнішні знання.

Предмет:
{subject}

Контекст:
{context}

Питання:
{question}
""".strip()